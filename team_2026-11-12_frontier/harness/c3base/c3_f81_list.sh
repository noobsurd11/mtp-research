#!/bin/bash
# c3base fix F8.1, step 1 of 2, gaint, READ ONLY. For every run with RD/.ok/<name> (and matching NAMES_RX):
# md5sum -c of the relayed copy on gaint must pass and md5(RUN.md5) must equal the .ok line; then the run goes into the
# list of the cv02 removal script (step 2). Step 2 re-checks on cv02, per run: md5(RUN.md5) equal to gaint's, exactly one
# dump dir at B/dumps/elbench1/<method>/<run>, and its file count equal to the RUN.md5 lines for that dir (so every file
# removed has a verified copy on gaint). Pattern = log/cv02_rm_dumps.sh (lead, 15 Nov).
# Writes only OUT (refuses if present). Runs nothing on cv02.
# Usage (G): RD=<relay dir> B=<cv02 deploy dir> [NAMES_RX=<regex>] CUDA_VISIBLE_DEVICES= nice -n 19 ionice -c3 bash c3_f81_list.sh OUT
#   rows2 (F8.1 a):    RD=/home/noob/work/bench_relay/rows2  B=/tmp/noob_el/bench_b12fca8
#   c3base (in run):   RD=/home/noob/work/bench_relay/c3base B=/tmp/noob_el/bench_89b9ea5 NAMES_RX=^c3_
set -u
RD=${RD:?relay dir}; B=${B:?cv02 deploy dir}; NAMES_RX=${NAMES_RX:-.}; OUT=${1:?output script}
echo "$B" | grep -qE '^/tmp/noob_el/bench_[0-9a-f]{7}$' || { echo "REFUSED: B $B"; exit 1; }
[ -e "$OUT" ] && { echo "REFUSED: $OUT exists"; exit 1; }
LIST=$(mktemp); ok=0; bad=0
for n in $(ls $RD/.ok | grep -v '\.refused$' | grep -E "$NAMES_RX" | sort); do
  m=$(awk '{print $4}' $RD/.ok/$n); r=$RD/$n
  [ -f $r/runs/$n/RUN.md5 ] || { echo "SKIP norun $n"; bad=$((bad+1)); continue; }
  [ "$(md5sum < $r/runs/$n/RUN.md5 | cut -c1-32)" = "$m" ] || { echo "SKIP md5(RUN.md5) != .ok $n"; bad=$((bad+1)); continue; }
  (cd $r && md5sum -c --quiet runs/$n/RUN.md5 > /dev/null 2>&1) || { echo "SKIP gaint md5sum -c FAIL $n"; bad=$((bad+1)); continue; }
  k=$(grep -cE "  dumps/elbench1/[A-Za-z0-9_]+/$n/" $r/runs/$n/RUN.md5)
  [ "$k" -gt 0 ] || { echo "SKIP no dump files in RUN.md5 $n"; bad=$((bad+1)); continue; }
  echo "$B $n $m $k" >> $LIST; ok=$((ok+1)); echo "OK $n RUN.md5 $m dump files $k (gaint md5sum -c OK)"
done
{ cat <<'HEAD'
# c3base F8.1 step 2 of 2: cv02 removal of relayed dump dirs (generated by harness/c3base/c3_f81_list.sh after gaint
# md5sum -c of each relayed copy passed). For rows2 this is the LEAD'S CALL (rows2 deploy dir). Run (G):
#   ssh -a -o BatchMode=yes cv02@10.8.1.106 "bash -s" < <this file>
# Removes only B/dumps/elbench1/<method>/<run> of the listed finished runs; checkpoints, configs and runs/ are kept.
n=0; bad=0; df -h /tmp | tail -1
while read B run md5 k; do
  f=$B/runs/$run/RUN.md5
  [ -f "$f" ] && [ "$(md5sum < $f | cut -c1-32)" = "$md5" ] || { echo "SKIP mismatch $run"; bad=$((bad+1)); continue; }
  d=$(ls -d $B/dumps/elbench1/*/$run 2>/dev/null)
  [ -n "$d" ] && [ "$(echo "$d" | wc -l)" = 1 ] || { echo "SKIP nodir $run"; bad=$((bad+1)); continue; }
  echo "$d" | grep -qE "^/tmp/noob_el/bench_[0-9a-f]{7}/dumps/elbench1/[A-Za-z0-9_]+/$run\$" && [ "${d%%/dumps/*}" = "$B" ] || { echo "SKIP path $d"; bad=$((bad+1)); continue; }
  c=$(find "$d" -type f | wc -l); [ "$c" = "$k" ] || { echo "SKIP count $run: $c files on cv02, $k verified"; bad=$((bad+1)); continue; }
  rm -rf -- "$d" && n=$((n+1)) && echo "$(date -u +%FT%T) removed $d ($k files; gaint copy verified, RUN.md5 $md5)" >> /tmp/noob_el/removed_relayed_dumps_c3base.log
done <<'LIST'
HEAD
cat $LIST; echo LIST
cat <<'TAIL'
echo "removed $n dump dirs; skipped $bad"; df -h /tmp | tail -1
TAIL
} > $OUT
chmod a-w $OUT; rm -f $LIST
echo "verified $ok, skipped $bad; wrote $OUT md5 $(md5sum < $OUT | cut -c1-32)"
