"""AL1 v2 analysis (protocol team_2026-10-21/alhvr/protocol_v2.md sections 5 and 9): P8 rule-1 arithmetic (as
scripts/ssl_rules.py), width check, gap closed, and a paired cell bootstrap for every pre-registered contrast, in the four
test-cell sets (all 50 / without the noisy cell / without the 7 twin test cells / without both), from E1 per-cell counts
(results/e1/raw_v2), checked first against the re-score JSONs (results/al1/raw). Also: step check (every scored
checkpoint is step 20,000, network A), per-run crack FP on the noisy cell, leave-top-3-out and source split for the
primary, val (descriptive), AP and bin-0 share (histograms), E1 task metrics. Model: scripts/sk1_analysis.py.
Usage: .venv/bin/python scripts/al1_analysis.py | tee results/al1/al1_analysis.md
"""
import glob, json, os
import numpy as np

NOISY = "CSIR_00070_r8_c4"
TWINS = ["CFVS_00006_r5_c5", "CFVS_00033_r8_c4", "CFVS_00035_r8_c4", "CFVS_00042_r8_c4", "CFVS_00018_r4_c4",
         "CFVS_00027_r4_c4", "ARTS_00020_r5_c1"]
SETS = [("all 50", []), ("without noisy cell", [NOISY]), ("without 7 twins", TWINS), ("without both", TWINS + [NOISY])]
ARMS = {k: [f"al1_{k}_s{i}" for i in range(5)] for k in ("A5", "AL5", "ALd5", "ALdh5", "CPS5", "CPSm5", "BsM5")}
TWO = ["AL5", "ALd5", "ALdh5", "CPS5", "CPSm5"]
PAIRS = [("AL5", "A5", "P, primary", "A5"),
         ("CPSm5", "CPS5", "S1, one change (routing)", "CPS5"),
         ("AL5", "ALd5", "S2, one change (CPCL)", "ALd5"),
         ("ALd5", "A5", "S3", "A5"), ("ALdh5", "A5", "S3", "A5"), ("CPS5", "A5", "S3", "A5"), ("CPSm5", "A5", "S3", "A5"),
         ("ALdh5", "ALd5", "S6, one change (λ)", "A5"),
         ("AL5", "CPSm5", "S4, method contrast", "A5")] + \
        [(t, "BsM5", "S5, descriptive", "A5") for t in TWO] + [("BsM5", "A5", "descriptive", "A5")]
NAMES = ["crack IoU", "inactive IoU", "crack relF1@2", "crack relP@2"]
CM = (("crack", "iou"), ("inactive", "iou"), ("crack", "rel_f1_2"), ("crack", "rel_p2"))
KEYS = ("crack_tp", "crack_gt", "crack_pred", "crack_p2_hit", "crack_r2_hit", "inact_tp", "inact_union")
RUNS = [r for rs in ARMS.values() for r in rs]

RS, ST = {}, {}
for f in glob.glob("results/al1/raw/al1_*_s[0-9].json"):
    for k, v in json.load(open(f)).items():
        RS[k] = v["new_escdd"]; ST[k] = (v.get("step"), v.get("weights"))
E1 = {r: json.load(open(f"results/e1/raw_v2/{r}.json")) for r in RUNS if os.path.exists(f"results/e1/raw_v2/{r}.json")}
missing = [r for r in RUNS if r not in E1 or f"test/{r}" not in RS or f"val/{r}" not in RS]
if missing:
    raise SystemExit(f"missing E1 or re-score JSONs: {missing}")

print("# AL1 v2 analysis (generated by scripts/al1_analysis.py)\n")
bad = {k: v for k, v in ST.items() if v[0] != 20000}
print(f"Step check: {len(ST)} re-score entries (test+val, 35 runs); step values {sorted({v[0] for v in ST.values()})}; "
      f"weights {sorted({str(v[1]) for v in ST.values()})}; not 20,000: {bad or 'none'}")
e1w = sorted({(str(E1[r].get("weights")), E1[r].get("step")) for r in RUNS})
print(f"E1 (weights, step) over 35 runs: {e1w}\n")

T = {r: E1[r]["cells"]["test"] for r in RUNS}
CELLS = sorted(T[RUNS[0]])
assert all(sorted(T[r]) == CELLS for r in RUNS) and len(CELLS) == 50
assert NOISY in CELLS and all(t in CELLS for t in TWINS)
C = {r: np.array([[T[r][c].get(k, 0) for k in KEYS] for c in CELLS], dtype=np.float64) for r in RUNS}


def metrics(t):  # t: (..., 7) summed counts
    ci = t[..., 0] / (t[..., 1] + t[..., 2] - t[..., 0])
    ii = t[..., 5] / t[..., 6]
    p, r = t[..., 3] / np.maximum(t[..., 2], 1), t[..., 4] / t[..., 1]
    return np.stack([ci, ii, 2 * p * r / (p + r), p], -1)


err = max(abs(metrics(C[r].sum(0))[j] - RS[f"test/{r}"][c][m]) for r in RUNS for j, (c, m) in enumerate(CM))
print(f"Sanity: max |E1 pooled - re-score JSON| over 35 runs, 4 metrics = {err:.1e}\n")


def rule(xa, xb):
    dl = xa.mean() - xb.mean()
    thr = max(0.01, 2 * np.sqrt((xa.std(ddof=1) ** 2 + xb.std(ddof=1) ** 2) / 3))
    return dl, thr, (1 if dl > thr else -1 if dl < -thr else 0)


# ---- per-arm tables from the re-score JSONs (test and val), AP
x = lambda arm, c, m, sp="test": np.array([RS[f"{sp}/{r}"][c][m] for r in ARMS[arm]])
cell = lambda v: f"{v.mean():.4f}±{v.std(ddof=1):.4f}"
print("## Per-arm, test (re-score JSONs, revised masks, 50 cells, mean±sd over 5 seeds)\n")
cols = list(CM) + [("crack", "ap"), ("inactive", "ap")]
print("| arm | " + " | ".join(f"{c} {m}" for c, m in cols) + " |\n|---|" + "---|" * len(cols))
for k in ARMS:
    print(f"| {k} | " + " | ".join(cell(x(k, c, m)) for c, m in cols) + " |")
print("\nPer seed (test crack IoU / inactive IoU / crack relF1@2):\n")
for k, rs in ARMS.items():
    print(f"- {k}: " + "; ".join(f"s{i} {RS[f'test/{r}']['crack']['iou']:.4f}/{RS[f'test/{r}']['inactive']['iou']:.4f}/"
                                 f"{RS[f'test/{r}']['crack']['rel_f1_2']:.4f}" for i, r in enumerate(rs)))
print("\n## Per-arm, val (54 cells; descriptive, never used for selection)\n")
print("| arm | crack IoU | inactive IoU | crack relF1@2 |\n|---|---|---|---|")
for k in ARMS:
    print(f"| {k} | " + " | ".join(cell(x(k, c, m, "val")) for c, m in CM[:3]) + " |")

# ---- gap closed reference (descriptive, cross-commit): L3@100% = P6 L3 100% s0-2 + P16 A 100% s3-4
REF = []
for f in ["results/p6/raw/p6_L3_100pct_s0.json", "results/p6/raw/p6_L3_100pct_s1.json", "results/p6/raw/p6_L3_100pct_s2.json",
          "results/p16/raw/p16_A_100pct_s3.json", "results/p16/raw/p16_A_100pct_s4.json"]:
    if os.path.exists(f):
        REF += [v["new_escdd"] for k, v in json.load(open(f)).items() if k.startswith("test/")]
ref = {cm: np.mean([d[cm[0]][cm[1]] for d in REF]) for cm in CM[:3]} if REF else None
print(f"\nGap-closed reference L3@100% (n={len(REF)} runs, cv02 P6 s0-2 + P16 s3-4, cross-commit, descriptive): "
      + (", ".join(f"{n} {ref[cm]:.4f}" for n, cm in zip(NAMES, CM[:3])) if ref else "missing"))

# ---- noisy cell
i_n = CELLS.index(NOISY)
print(f"\n## Crack FP px on {NOISY} per run (E1 crack_pred - crack_tp)\n")
for k, rs in ARMS.items():
    print(f"- {k}: " + ", ".join(f"s{r[-1]} {int(C[r][i_n, 2] - C[r][i_n, 0])}" for r in rs))

# ---- rule tables per cell set, with paired cell bootstrap
rng = np.random.default_rng(0)
B = 2000
word = {1: "BETTER", -1: "WORSE", 0: "n.d."}
for lab, drop in SETS:
    keep = np.array([c not in drop for c in CELLS])
    idx = np.flatnonzero(keep)
    boot = rng.integers(0, len(idx), size=(B, len(idx)))
    V = {k: np.array([metrics(C[r][keep].sum(0)) for r in rs]) for k, rs in ARMS.items()}
    BV = {k: np.mean([metrics(C[r][idx][boot].sum(1)) for r in rs], 0) for k, rs in ARMS.items()}
    print(f"\n## {lab} ({keep.sum()} cells)\n\n| arm | " + " | ".join(NAMES) + " |\n|---|" + "---|" * len(NAMES))
    for k, v in V.items():
        print(f"| {k} | " + " | ".join(f"{v[:, j].mean():.4f}±{v[:, j].std(ddof=1):.4f}" for j in range(4)) + " |")
    print("\n| contrast | role | " + " | ".join(NAMES[:3]) + " | rule-1 arithmetic | relP@2 Δ (vs parent) |"
          + (" gap closed (crack / inact / relF1) |" if lab == "all 50" else "") + "\n|---|---|---|---|---|---|---|"
          + ("---|" if lab == "all 50" else ""))
    for s, b, role, wpar in PAIRS:
        cells, sg = [], []
        for j in range(3):
            dl, thr, sgn = rule(V[s][:, j], V[b][:, j]); sg.append(sgn)
            lo, hi = np.percentile(BV[s][:, j] - BV[b][:, j], [2.5, 97.5])
            cells.append(f"{dl:+.4f} ({thr:.4f}) [{lo:+.4f}, {hi:+.4f}]")
        w = "WORSE" if -1 in sg else "passes" if 1 in sg else "n.d."
        dp = V[s][:, 3].mean() - V[wpar][:, 3].mean()
        gc = ""
        if lab == "all 50" and ref and b != "A5":
            gc = " – |"
        elif lab == "all 50" and ref:
            gc = " " + " / ".join(f"{(V[s][:, j].mean() - V['A5'][:, j].mean()) / (ref[CM[j]] - V['A5'][:, j].mean()):+.2f}"
                                  for j in range(3)) + " |"
        print(f"| {s} − {b} | {role} | " + " | ".join(cells) + f" | {w} | {dp:+.4f} vs {wpar}"
              + (" FLAG" if dp < -0.05 else "") + " |" + gc)
print("\nCells: Δ (rule-1 threshold) [95% paired cell-bootstrap CI of the seed-mean Δ, 2,000 resamples, rng seed 0]."
      " Gap closed = (X − A5)/(L3@100% − A5), all 50 cells, descriptive.")

# ---- primary: leave-top-3-out (by GT area of that class) and source split
print("\n## Primary AL5 − A5: leave-top-3-out and source split (all 50 cells; descriptive)\n")
gt_c, gt_i = C[RUNS[0]][:, 1], np.array([T[RUNS[0]][c].get("inact_gt", 0) for c in CELLS])
for lab, keep in [("leave top-3 crack-GT cells out", ~np.isin(np.arange(50), np.argsort(-gt_c)[:3])),
                  ("leave top-3 inactive-GT cells out", ~np.isin(np.arange(50), np.argsort(-gt_i)[:3])),
                  ("CSIR+ARTS cells", np.array([c.startswith(("CSIR", "ARTS")) for c in CELLS])),
                  ("other sources", np.array([not c.startswith(("CSIR", "ARTS")) for c in CELLS]))]:
    Va = np.array([metrics(C[r][keep].sum(0)) for r in ARMS["AL5"]]); Vb = np.array([metrics(C[r][keep].sum(0)) for r in ARMS["A5"]])
    print(f"- {lab} ({keep.sum()} cells): " + ", ".join(
        f"{n} {Va[:, j].mean() - Vb[:, j].mean():+.4f}" for j, n in enumerate(NAMES[:3])))

